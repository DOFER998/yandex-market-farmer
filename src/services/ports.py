"""Dependencies required by application services, implemented by adapters."""

from collections.abc import Callable
from contextlib import AbstractAsyncContextManager, AbstractContextManager
from dataclasses import dataclass
from pathlib import Path
from typing import Protocol

from src.database.models import Account, BalanceSnapshot, BonusStatus, FarmRun, Operation
from src.market.live import LiveState
from src.market.live_client import LiveCursor
from src.market.models import DailyClaim, DailyStatus, GameClaim, Hub, Level
from src.market.wheel_missions import WheelMission, WheelMissionAttempt


@dataclass(frozen=True, slots=True)
class RunStatistics:
    collections: int
    failures: int


class Accounts(Protocol):
    async def delete(self, account_id: str) -> None: ...
    async def save(self, account: Account) -> None: ...
    async def get(self, account_id: str) -> Account: ...
    async def list(self) -> list[Account]: ...


class Runs(Protocol):
    async def bonus_status(self, account_id: str, source: str) -> BonusStatus | None: ...
    async def save(
        self, *rows: Account | FarmRun | Operation | BalanceSnapshot | BonusStatus
    ) -> None: ...
    async def history(self, account_id: str, limit: int = 10) -> list[FarmRun]: ...
    async def operations(self, account_id: str, run_id: str | None = None) -> list[Operation]: ...
    async def statistics(self, account_id: str) -> RunStatistics: ...
    async def recover(self, account: Account) -> bool: ...


class Locks(Protocol):
    def guard(self, account_id: str) -> AbstractAsyncContextManager[None]: ...


class RewardsClient(Protocol):
    def check_auth(self) -> None: ...
    def balance(self) -> int: ...
    def daily_status(self) -> DailyStatus: ...
    def claim_daily(self) -> DailyClaim: ...
    def games(self) -> Hub: ...
    def wheel_missions(self) -> list[WheelMission]: ...
    def complete_free_wheel_mission(self, mission_id: str) -> WheelMissionAttempt: ...
    def claim_game(self, game_id: str) -> GameClaim: ...
    def claim_mission(self, mission_id: str) -> GameClaim: ...
    def game_levels(self, game_id: str) -> list[Level]: ...


type ClientFactory = Callable[[Path], AbstractContextManager[RewardsClient]]


class LiveRewardsClient(Protocol):
    def check_auth(self, *, force: bool = True): ...
    def balance(self) -> int: ...
    def bootstrap_live(self) -> LiveCursor: ...
    def poll_live(self, cursor: LiveCursor) -> LiveState: ...


type LiveClientFactory = Callable[[Path], AbstractContextManager[LiveRewardsClient]]
